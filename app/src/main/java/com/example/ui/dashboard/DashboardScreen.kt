@Composable
fun InspectionCard(
    inspection: Inspection,
    compliances: List<Compliance> = emptyList(),
    forceExpanded: Boolean = false,
    onViewDossier: (() -> Unit)? = null,
    onEdit: (() -> Unit)? = null,
    onDelete: (() -> Unit)? = null,
    onClick: () -> Unit
) {
    val dateFormat = SimpleDateFormat("MMM dd, yyyy", Locale.getDefault())
    val dateString = if (inspection.scheduledDate > 0) dateFormat.format(Date(inspection.scheduledDate)) else "Not Scheduled"

    val isLocationTbd = inspection.locationName.isBlank() || inspection.locationName.equals("TBD", ignoreCase = true)

    val pendingCount = compliances.count { it.status != ComplianceStatus.RESOLVED && it.status != ComplianceStatus.CLOSED }
    var isCompliancesExpanded by remember { mutableStateOf(forceExpanded) }
    LaunchedEffect(forceExpanded) {
        isCompliancesExpanded = forceExpanded
    }

    val actionLabel = when (inspection.status) {
        InspectionStatus.ASSIGNED, InspectionStatus.ACCEPTED -> "Start"
        InspectionStatus.IN_PROGRESS -> "Continue"
        InspectionStatus.COMPLETED -> "Review"
        else -> "Open"
    }

    val actionIcon = when (inspection.status) {
        InspectionStatus.COMPLETED -> Icons.Default.Visibility
        InspectionStatus.IN_PROGRESS -> Icons.Default.Edit
        else -> Icons.Default.PlayArrow
    }

    val isDark = isSystemInDarkTheme()

    Card(
        modifier = Modifier
            .fillMaxWidth()
            .clickable(onClick = onClick),
        shape = RoundedCornerShape(12.dp),
        colors = CardDefaults.cardColors(
            containerColor = MaterialTheme.colorScheme.surface
        ),
        border = BorderStroke(
            1.dp,
            MaterialTheme.colorScheme.outlineVariant
        ),
        elevation = CardDefaults.cardElevation(defaultElevation = 1.5.dp)
    ) {
        Column(modifier = Modifier.padding(16.dp)) {
            // Top Row: Square Icon Box, Middle Titles + Category Badge, Trailing Status Pill
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically
            ) {
                val (iconBg, iconFg) = when {
                    inspection.inspectionTypeName.contains("Station", ignoreCase = true) -> Color(0xFFFFF7ED) to Color(0xFFEA580C)
                    inspection.inspectionTypeName.contains("Footplate", ignoreCase = true) -> Color(0xFFFFF7ED) to Color(0xFFEA580C)
                    inspection.isSpotInspection -> Color(0xFFFEF3C7) to Color(0xFFB45309)
                    else -> Color(0xFFFFF7ED) to Color(0xFFEA580C)
                }

                Surface(
                    color = iconBg,
                    shape = RoundedCornerShape(10.dp),
                    border = BorderStroke(1.dp, iconFg.copy(alpha = 0.2f)),
                    modifier = Modifier.size(44.dp)
                ) {
                    Box(contentAlignment = Alignment.Center) {
                        Icon(
                            imageVector = when {
                                inspection.inspectionTypeName.contains("Station", ignoreCase = true) -> Icons.Default.Place
                                inspection.inspectionTypeName.contains("Footplate", ignoreCase = true) -> Icons.Default.Train
                                else -> Icons.Default.Assignment
                            },
                            contentDescription = null,
                            tint = iconFg,
                            modifier = Modifier.size(24.dp)
                        )
                    }
                }

                Spacer(modifier = Modifier.width(12.dp))

                Column(modifier = Modifier.weight(1f)) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Text(
                            text = inspection.inspectionNumber.ifEmpty { "INSPECTION" },
                            fontWeight = FontWeight.Bold,
                            color = Color(0xFFEA580C)
                        )
                        if (inspection.isSpotInspection) {
                            Spacer(modifier = Modifier.width(6.dp))
                            Surface(
                                color = if (inspection.inspectionCategory == "SELF") Color(0xFFFFF7ED) else Color(0xFFFEF3C7),
                                shape = RoundedCornerShape(4.dp),
                                border = BorderStroke(1.dp, if (inspection.inspectionCategory == "SELF") Color(0xFFFFEDD5) else Color(0xFFFDE68A))
                            ) {
                                Row(
                                    modifier = Modifier.padding(horizontal = 6.dp, vertical = 2.dp),
                                    verticalAlignment = Alignment.CenterVertically
                                ) {
                                    Icon(
                                        imageVector = if (inspection.inspectionCategory == "SELF") Icons.Default.AssignmentInd else Icons.Default.FlashOn,
                                        contentDescription = null,
                                        modifier = Modifier.size(11.dp),
                                        tint = if (inspection.inspectionCategory == "SELF") Color(0xFFC2410C) else Color(0xFFB45309)
                                    )
                                    Spacer(modifier = Modifier.width(3.dp))
                                    Text(
                                        text = if (inspection.inspectionCategory == "SELF") "SELF" else "SPOT",
                                        style = MaterialTheme.typography.labelSmall,
                                        fontWeight = FontWeight.ExtraBold,
                                        color = if (inspection.inspectionCategory == "SELF") Color(0xFFC2410C) else Color(0xFFB45309)
                                    )
                                }
                            }
                        }
                    }
                    Text(
                        text = inspection.inspectionTypeName.ifEmpty { "General Inspection" },
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.SemiBold,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                }

                val (statusBg, statusFg) = when (inspection.status) {
                    InspectionStatus.COMPLETED -> Color(0xFFDCFCE7) to Color(0xFF166534)
                    InspectionStatus.IN_PROGRESS -> Color(0xFFFFF7ED) to Color(0xFFEA580C)
                    InspectionStatus.ASSIGNED -> Color(0xFFFEF3C7) to Color(0xFF92400E)
                    InspectionStatus.ACCEPTED -> Color(0xFFEFF5FA) to Color(0xFF2B5B84)
                    else -> MaterialTheme.colorScheme.surfaceVariant to MaterialTheme.colorScheme.onSurfaceVariant
                }

                Surface(
                    color = statusBg,
                    shape = RoundedCornerShape(6.dp),
                    border = BorderStroke(1.dp, statusFg.copy(alpha = 0.25f))
                ) {
                    Text(
                        text = inspection.status.name.replace("_", " "),
                        style = MaterialTheme.typography.labelSmall,
                        color = statusFg,
                        modifier = Modifier.padding(horizontal = 8.dp, vertical = 4.dp),
                        fontWeight = FontWeight.Bold
                    )
                }
            }

            Spacer(modifier = Modifier.height(10.dp))

            // Location Highlight
            Row(
                verticalAlignment = Alignment.CenterVertically,
                modifier = Modifier.fillMaxWidth()
            ) {
                Icon(
                    Icons.Default.LocationOn,
                    contentDescription = null,
                    tint = if (isLocationTbd) MaterialTheme.colorScheme.error else MaterialTheme.colorScheme.primary,
                    modifier = Modifier.size(18.dp)
                )
                Spacer(modifier = Modifier.width(6.dp))
                Text(
                    text = "Location: ${if (isLocationTbd) "TBD" else inspection.locationName}",
                    style = MaterialTheme.typography.bodyMedium,
                    fontWeight = FontWeight.Medium,
                    color = if (isLocationTbd) MaterialTheme.colorScheme.error else MaterialTheme.colorScheme.onSurface
                )
            }

            Spacer(modifier = Modifier.height(4.dp))

            // Officer & Scheduled Date
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Text(
                    "Officer: ${inspection.assignedOfficerName.ifEmpty { "Unassigned" }}",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
                Text(
                    "Scheduled: $dateString",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }

            // Execution Date & Diff alert (preserved card-wise)
            val execDate = inspection.executionDate
            if (execDate != null && execDate > 0) {
                Spacer(modifier = Modifier.height(2.dp))
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Text(
                        text = "Executed: ${dateFormat.format(Date(execDate))}",
                        style = MaterialTheme.typography.bodySmall,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.primary
                    )
                }
            }
            if (inspection.executionDate != null && inspection.executionDate!! > 0 && inspection.scheduledDate > 0) {
                val cal1 = java.util.Calendar.getInstance().apply { timeInMillis = inspection.executionDate!! }
                val cal2 = java.util.Calendar.getInstance().apply { timeInMillis = inspection.scheduledDate }
                val isDiff = cal1.get(java.util.Calendar.YEAR) != cal2.get(java.util.Calendar.YEAR) ||
                             cal1.get(java.util.Calendar.DAY_OF_YEAR) != cal2.get(java.util.Calendar.DAY_OF_YEAR)
                if (isDiff) {
                    Text(
                        text = "Scheduled: $dateString (Executed on different date)",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.tertiary,
                        modifier = Modifier.padding(top = 2.dp)
                    )
                }
            }

            // Compliance status indicator tag on inspection card (Matching screenshot 1)
            if (compliances.isNotEmpty()) {
                Spacer(modifier = Modifier.height(8.dp))
                Surface(
                    color = if (pendingCount > 0) Color(0xFFFEE2E2) else Color(0xFFE8F1F8),
                    shape = RoundedCornerShape(8.dp),
                    border = BorderStroke(1.dp, if (pendingCount > 0) Color(0xFFFECACA) else Color(0xFFCBD5E1)),
                    modifier = Modifier
                        .fillMaxWidth()
                        .clickable { isCompliancesExpanded = !isCompliancesExpanded }
                ) {
                    Row(
                        modifier = Modifier.padding(horizontal = 10.dp, vertical = 6.dp),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Row(
                            verticalAlignment = Alignment.CenterVertically,
                            modifier = Modifier.weight(1f, fill = false)
                        ) {
                            Icon(
                                if (pendingCount > 0) Icons.Default.PendingActions else Icons.Default.AssignmentTurnedIn,
                                contentDescription = null,
                                modifier = Modifier.size(16.dp),
                                tint = if (pendingCount > 0) Color(0xFFDC2626) else Color(0xFFEA580C)
                            )
                            Spacer(modifier = Modifier.width(6.dp))
                            Text(
                                text = if (pendingCount > 0)
                                    "${compliances.size} Compliances raised ($pendingCount pending)"
                                else
                                    "${compliances.size} Compliances raised (All Resolved)",
                                style = MaterialTheme.typography.labelSmall,
                                fontWeight = FontWeight.Bold,
                                color = if (pendingCount > 0) Color(0xFF991B1B) else Color(0xFF9A3412)
                            )
                        }

                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Text(
                                text = if (isCompliancesExpanded) "Hide" else "View Details",
                                style = MaterialTheme.typography.labelSmall,
                                fontWeight = FontWeight.SemiBold,
                                color = if (pendingCount > 0) Color(0xFF991B1B) else Color(0xFFEA580C)
                            )
                            Icon(
                                if (isCompliancesExpanded) Icons.Default.KeyboardArrowUp else Icons.Default.KeyboardArrowDown,
                                contentDescription = null,
                                modifier = Modifier.size(16.dp),
                                tint = if (pendingCount > 0) Color(0xFF991B1B) else Color(0xFFEA580C)
                            )
                        }
                    }
                }

                // Expandable point-level compliance items under the inspection card
                AnimatedVisibility(
                    visible = isCompliancesExpanded,
                    enter = expandVertically() + fadeIn(),
                    exit = shrinkVertically() + fadeOut()
                ) {
                    Column(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(top = 8.dp),
                        verticalArrangement = Arrangement.spacedBy(6.dp)
                    ) {
                        compliances.forEach { comp ->
                            Surface(
                                color = Color(0xFFF8FAFC),
                                shape = RoundedCornerShape(6.dp),
                                border = BorderStroke(0.5.dp, Color(0xFFCBD5E1)),
                                modifier = Modifier.fillMaxWidth()
                            ) {
                                Column(modifier = Modifier.padding(8.dp)) {
                                    Row(
                                        modifier = Modifier.fillMaxWidth(),
                                        horizontalArrangement = Arrangement.SpaceBetween,
                                        verticalAlignment = Alignment.CenterVertically
                                    ) {
                                        Text(
                                            text = comp.title,
                                            style = MaterialTheme.typography.labelMedium,
                                            fontWeight = FontWeight.Bold,
                                            color = Color(0xFF0F172A),
                                            modifier = Modifier.weight(1f)
                                        )
                                        Surface(
                                            color = when (comp.status) {
                                                ComplianceStatus.RESOLVED, ComplianceStatus.CLOSED -> Color(0xFF2E7D32).copy(alpha = 0.15f)
                                                ComplianceStatus.UNDER_ACTION -> MaterialTheme.colorScheme.tertiary.copy(alpha = 0.15f)
                                                else -> Color(0xFFB71C1C).copy(alpha = 0.15f)
                                            },
                                            shape = RoundedCornerShape(4.dp)
                                        ) {
                                            Text(
                                                text = comp.status.name.replace("_", " "),
                                                color = when (comp.status) {
                                                    ComplianceStatus.RESOLVED, ComplianceStatus.CLOSED -> Color(0xFF2E7D32)
                                                    ComplianceStatus.UNDER_ACTION -> MaterialTheme.colorScheme.tertiary
                                                    else -> Color(0xFFB71C1C)
                                                },
                                                style = MaterialTheme.typography.labelSmall,
                                                fontWeight = FontWeight.Bold,
                                                modifier = Modifier.padding(horizontal = 4.dp, vertical = 1.dp)
                                            )
                                        }
                                    }

                                    if (comp.inspectionPointTitle.isNotBlank() && comp.inspectionPointTitle != comp.title) {
                                        Text(
                                            text = "Point: ${comp.inspectionPointTitle}",
                                            style = MaterialTheme.typography.labelSmall,
                                            color = MaterialTheme.colorScheme.primary,
                                            fontWeight = FontWeight.SemiBold
                                        )
                                    }

                                    if (comp.description.isNotBlank()) {
                                        Text(
                                            text = comp.description,
                                            style = MaterialTheme.typography.bodySmall,
                                            color = MaterialTheme.colorScheme.onSurfaceVariant
                                        )
                                    }

                                    Row(
                                        modifier = Modifier
                                            .fillMaxWidth()
                                            .padding(top = 2.dp),
                                        horizontalArrangement = Arrangement.SpaceBetween
                                    ) {
                                        Text(
                                            text = "Assigned: ${comp.assignedOfficerName.ifBlank { "Unassigned" }}",
                                            style = MaterialTheme.typography.labelSmall,
                                            color = MaterialTheme.colorScheme.onSurfaceVariant
                                        )
                                        if (comp.targetDate > 0) {
                                            Text(
                                                text = "Target: ${dateFormat.format(Date(comp.targetDate))}",
                                                style = MaterialTheme.typography.labelSmall,
                                                color = if (comp.targetDate < System.currentTimeMillis() && comp.status != ComplianceStatus.RESOLVED && comp.status != ComplianceStatus.CLOSED)
                                                    MaterialTheme.colorScheme.error
                                                else MaterialTheme.colorScheme.onSurfaceVariant
