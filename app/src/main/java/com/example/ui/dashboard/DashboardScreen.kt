@Composable
fun GroupedComplianceItemCard(
    compliance: Compliance,
    currentUserId: String = "",
    currentUserName: String = "",
    onTakeAction: () -> Unit
) {
    val dateFormat = SimpleDateFormat("dd MMM yyyy", Locale.getDefault())
    val targetDateStr = if (compliance.targetDate != null && compliance.targetDate!! > 0)
        dateFormat.format(Date(compliance.targetDate!!)) else "No target date"

    val statusColor = when (compliance.status) {
        ComplianceStatus.RESOLVED, ComplianceStatus.CLOSED -> Color(0xFF2E7D32)
        ComplianceStatus.UNDER_ACTION -> MaterialTheme.colorScheme.tertiary
        else -> MaterialTheme.colorScheme.error
    }

    val isGeneratedByMe = (currentUserId.isNotBlank() && compliance.inspectingOfficerId == currentUserId) ||
        (currentUserName.isNotBlank() && compliance.inspectingOfficerName.equals(currentUserName, ignoreCase = true))
    val isAssignedToMe = (currentUserId.isNotBlank() && compliance.assignedOfficerId == currentUserId) ||
        (currentUserName.isNotBlank() && compliance.assignedOfficerName.equals(currentUserName, ignoreCase = true))

    Card(
        modifier = Modifier.fillMaxWidth(),
        shape = RoundedCornerShape(10.dp),
        colors = CardDefaults.cardColors(
            containerColor = Color.White,
            contentColor = Color(0xFF0F172A)
        ),
        border = BorderStroke(1.dp, Color(0xFFE2E8F0)),
        elevation = CardDefaults.cardElevation(defaultElevation = 1.dp)
    ) {
        Column(modifier = Modifier.padding(12.dp)) {
            // Badges row
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Surface(
                    color = when (compliance.severity) {
                        ComplianceSeverity.CRITICAL -> MaterialTheme.colorScheme.errorContainer
                        ComplianceSeverity.MAJOR -> MaterialTheme.colorScheme.tertiaryContainer
                        ComplianceSeverity.MINOR -> MaterialTheme.colorScheme.primaryContainer
                    },
                    shape = RoundedCornerShape(6.dp)
                ) {
                    Text(
                        "${compliance.severity.name} PRIORITY",
                        style = MaterialTheme.typography.labelSmall,
                        fontWeight = FontWeight.Bold,
                        modifier = Modifier.padding(horizontal = 6.dp, vertical = 2.dp)
                    )
                }

                Surface(
                    color = statusColor.copy(alpha = 0.15f),
                    shape = RoundedCornerShape(6.dp)
                ) {
                    Text(
                        compliance.status.name.replace("_", " "),
                        color = statusColor,
                        style = MaterialTheme.typography.labelSmall,
                        fontWeight = FontWeight.Bold,
                        modifier = Modifier.padding(horizontal = 6.dp, vertical = 2.dp)
                    )
                }
            }

            Spacer(modifier = Modifier.height(6.dp))

            // Role indicator banner
            Surface(
                color = when {
                    isAssignedToMe -> Color(0xFFEFF6FF)
                    isGeneratedByMe -> Color(0xFFFAF5FF)
                    else -> Color(0xFFF1F5F9)
                },
                shape = RoundedCornerShape(6.dp),
                border = BorderStroke(
                    0.5.dp,
                    when {
                        isAssignedToMe -> Color(0xFF93C5FD)
                        isGeneratedByMe -> Color(0xFFD8B4FE)
                        else -> Color(0xFFCBD5E1)
                    }
                ),
                modifier = Modifier.fillMaxWidth()
            ) {
                Row(
                    modifier = Modifier.padding(horizontal = 8.dp, vertical = 3.dp),
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Text(
                        text = when {
                            isAssignedToMe -> "📥 Assigned to You • By: ${compliance.inspectingOfficerName.ifBlank { "Inspecting Officer" }}"
                            isGeneratedByMe -> "📤 Generated by You • To: ${compliance.assignedOfficerName.ifBlank { "Assigned Officer" }}"
                            else -> "👮 To: ${compliance.assignedOfficerName.ifBlank { "Officer" }} • By: ${compliance.inspectingOfficerName.ifBlank { "Officer" }}"
                        },
                        style = MaterialTheme.typography.labelSmall,
                        fontWeight = FontWeight.Bold,
                        color = when {
                            isAssignedToMe -> Color(0xFF1E40AF)
                            isGeneratedByMe -> Color(0xFF6B21A8)
                            else -> Color(0xFF334155)
                        }
                    )
                }
            }

            Spacer(modifier = Modifier.height(6.dp))

            Text(
                compliance.inspectionPointTitle.ifEmpty { compliance.title.ifEmpty { "Observation Item" } },
                style = MaterialTheme.typography.titleSmall,
                fontWeight = FontWeight.Bold,
                color = MaterialTheme.colorScheme.onSurface
            )

            Spacer(modifier = Modifier.height(4.dp))

            Surface(
                color = MaterialTheme.colorScheme.surface,
                shape = RoundedCornerShape(6.dp),
                border = BorderStroke(0.5.dp, MaterialTheme.colorScheme.outlineVariant),
                modifier = Modifier.fillMaxWidth()
            ) {
                Column(modifier = Modifier.padding(8.dp)) {
                    Text(
                        "Observation / Deficiency:",
                        style = MaterialTheme.typography.labelSmall,
                        fontWeight = FontWeight.Bold,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                    Text(
                        compliance.description.ifBlank { "No description entered." },
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurface
                    )
                }
            }

            if (compliance.complianceRemarks.isNotBlank()) {
                Spacer(modifier = Modifier.height(6.dp))
                Surface(
                    color = MaterialTheme.colorScheme.primaryContainer.copy(alpha = 0.4f),
                    shape = RoundedCornerShape(6.dp),
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Column(modifier = Modifier.padding(8.dp)) {
                        Text(
                            "Your Action Remarks:",
                            style = MaterialTheme.typography.labelSmall,
                            fontWeight = FontWeight.Bold,
                            color = MaterialTheme.colorScheme.primary
                        )
                        Text(
                            compliance.complianceRemarks,
                            style = MaterialTheme.typography.bodySmall
                        )
                    }
                }
            }

            Spacer(modifier = Modifier.height(8.dp))

            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(
                        Icons.Default.AccessTime,
                        contentDescription = null,
                        modifier = Modifier.size(14.dp),
                        tint = MaterialTheme.colorScheme.outline
                    )
                    Spacer(modifier = Modifier.width(4.dp))
                    Text(
                        "Target: $targetDateStr",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.outline
                    )
                }

                Button(
                    onClick = onTakeAction,
                    contentPadding = PaddingValues(horizontal = 12.dp, vertical = 4.dp),
                    shape = RoundedCornerShape(8.dp)
                ) {
                    Icon(
                        if (compliance.status == ComplianceStatus.RESOLVED) Icons.Default.Edit else Icons.Default.Check,
                        contentDescription = null,
                        modifier = Modifier.size(14.dp)
                    )
                    Spacer(modifier = Modifier.width(4.dp))
                    Text(
                        if (compliance.status == ComplianceStatus.RESOLVED) "Update Remarks" else "Take Action",
                        style = MaterialTheme.typography.labelMedium
                    )
                }
            }
        }
    }
}

